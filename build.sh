#!/usr/bin/env bash
# Builds the C++ planning engine to WebAssembly and embeds it in js/engine-wasm.js
# (embedding as base64 lets the app work when index.html is opened straight from disk).
# Requires: clang++ and wasm-ld (LLVM)   — or set CXX to another wasm-capable clang.
set -euo pipefail
cd "$(dirname "$0")"
CXX="${CXX:-clang++}"
mkdir -p wasm
"$CXX" --target=wasm32 -O3 -nostdlib -fno-exceptions -fno-rtti -fvisibility=hidden \
  -Wl,--no-entry -Wl,--export-dynamic -Wl,--strip-all \
  -o wasm/planner.wasm cpp/planner.cpp
echo "// Auto-generated by build.sh from cpp/planner.cpp — do not edit." > js/engine-wasm.js
printf 'window.FLOWDECK_WASM="%s";\n' "$(base64 -w0 wasm/planner.wasm)" >> js/engine-wasm.js
echo "Built wasm/planner.wasm ($(wc -c < wasm/planner.wasm) bytes) and js/engine-wasm.js"
